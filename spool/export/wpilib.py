"""WPILib export: Constants.java + feedforward objects + SysId field map.

Verified against docs.wpilib.org (see docs/VERIFIED_APIS.md):

  SimpleMotorFeedforward(kS, kV, kA).calculate(velocity, acceleration)
  ArmFeedforward(kS, kG, kV, kA).calculate(position, velocity, acceleration)
  ElevatorFeedforward(kS, kG, kV, kA).calculate(velocity, acceleration)

Units follow WPILib: volts, volts/(unit/s), volts/(unit/s^2). ArmFeedforward
takes position in radians, so an arm's kG is volts at horizontal and the class
applies cos(position) itself -- Spool's kG is defined the same way, which is why
the conversion is a straight pass-through.

SysId note: SysId's documented input is a WPILog file (docs "Loading Data"),
reading entries named "sysid-test-state-<mechanism>" plus Position/Velocity/
Voltage. Spool therefore does not fabricate a JSON dataset schema; it emits a
field map (`sysid_fields.json`) that SpoolCalibrate's wpilog satisfies, so the log
drops straight into SysId.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from string import Template

TEMPLATE = Template(
    """package frc.robot;

// -----------------------------------------------------------------------------
// Generated by Spool. FRC-equivalent configuration of the same mechanisms that
// the FTC robot has, so the same CAD numbers drive both codebases.
// Units: SI (volts, metres, radians, seconds). ArmFeedforward takes radians.
// -----------------------------------------------------------------------------

import edu.wpi.first.math.controller.ArmFeedforward;
import edu.wpi.first.math.controller.PIDController;
import edu.wpi.first.math.controller.SimpleMotorFeedforward;

public final class Constants {
    private Constants() {}

${blocks}
}
"""
)

BLOCK = Template(
    """    /** ${label} */
    public static final class ${cls} {
        public static final double kS = ${kS};
        public static final double kV = ${kV};
        public static final double kA = ${kA};
${kg_line}
        public static final ${ff_class} FEEDFORWARD =
                new ${ff_class}(${ff_args});
        public static final double kP = ${kP};
        public static final double kI = ${kI};
        public static final double kD = ${kD};
        public static final PIDController PID = new PIDController(kP, kI, kD);
    }
"""
)


def _cls(name: str) -> str:
    return "".join(p.capitalize() for p in name.replace("-", "_").split("_"))


def build_wpilib(model, robot_doc: dict, gains_table: list[dict], outdir: str | Path) -> dict[str, Path]:
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    blocks = []
    fields = []

    for entry in gains_table:
        g = entry["gains"]
        tune = entry.get("tuned", {})
        kind = entry.get("kind", "rotary")
        cls = _cls(entry["name"])
        label = entry.get("label", entry["name"])

        if kind == "arm":
            ff_class = "ArmFeedforward"
            ff_args = "kS, kG, kV, kA"
            kg_line = f"        public static final double kG = {g['kG']:.6f};"
            sysid_mechanism = "Arm"
            units = {"position": "rad", "velocity": "rad/s"}
        elif kind == "elevator":
            ff_class = "ElevatorFeedforward"
            ff_args = "kS, kG, kV, kA"
            kg_line = f"        public static final double kG = {g['kG']:.6f};"
            sysid_mechanism = "Elevator"
            units = {"position": "m", "velocity": "m/s"}
        else:
            ff_class = "SimpleMotorFeedforward"
            ff_args = "kS, kV, kA"
            kg_line = "        // no gravity term on this axis"
            sysid_mechanism = "Simple"
            units = {"velocity": "rad/s" if kind == "rotary" else "m/s"}

        blocks.append(
            BLOCK.substitute(
                label=label,
                cls=cls,
                kS=f"{g['kS']:.6f}",
                kV=f"{g['kV']:.6f}",
                kA=f"{g['kA']:.6f}",
                kg_line=kg_line,
                ff_class=ff_class,
                ff_args=ff_args,
                kP=f"{tune.get('kp', 0.0):.6f}",
                kI=f"{tune.get('ki', 0.0):.6f}",
                kD=f"{tune.get('kd', 0.0):.6f}",
            )
        )
        fields.append(
            {
                "name": entry["name"],
                "java_class": cls,
                "sysid_mechanism": sysid_mechanism,
                "sysid_state_entry": f"sysid-test-state-{entry['name']}",
                "units": units,
                "feedforward": ff_class,
                "gains": g,
            }
        )

    constants = outdir / "Constants.java"
    constants.write_text(
        TEMPLATE.substitute(blocks="\n".join(blocks)), encoding="utf-8"
    )

    sysid = outdir / "sysid_fields.json"
    sysid.write_text(
        json.dumps(
            {
                "note": (
                    "SysId's input is a .wpilog. These are the log entry names "
                    "SpoolCalibrate writes, matching docs.wpilib.org 'Loading Data'."
                ),
                "log_entry_conventions": {
                    "state": "sysid-test-state-<mechanism>  (string)",
                    "voltage": "spool/<mechanism>/Voltage  (double, volts)",
                    "position": "spool/<mechanism>/Position (double)",
                    "velocity": "spool/<mechanism>/Velocity (double)",
                },
                "mechanisms": fields,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return {"constants": constants, "sysid_fields": sysid}


def build_sysid_routine_notes(outdir: str | Path) -> Path:
    """A short operator note next to Constants.java."""
    outdir = Path(outdir)
    path = outdir / "SYSID.md"
    path.write_text(
        "# Characterising the FRC-equivalent mechanisms\n\n"
        "1. Deploy `spool/runtime/frc/SpoolCalibrate.java` as a command.\n"
        "2. It logs, via DataLogManager, to a .wpilog:\n"
        "   - `sysid-test-state-<mechanism>` (string)\n"
        "   - `spool/<mechanism>/Voltage`, `/Position`, `/Velocity`\n"
        "3. Open the .wpilog in SysId, drag the entries into the Data Selector\n"
        "   (docs.wpilib.org -> Software -> Advanced Controls -> System Identification\n"
        "   -> Loading Data), then run the analysis for the mechanism type listed in\n"
        "   `sysid_fields.json`.\n"
        "4. SysId's kS/kV/kA replace the Spool values in `Constants.java`; kS is\n"
        "   *expected* to differ most, because Spool models friction instead of\n"
        "   measuring it.\n",
        encoding="utf-8",
    )
    return path
