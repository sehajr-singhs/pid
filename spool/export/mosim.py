"""MoSim export.

What was verified this session (docs/VERIFIED_APIS.md has the URLs):
  * MoSim mods are folders containing `<Mod>.bundle`, `<Mod>.dll`, `catalog.json`
    (plus `catalog.hash` and `settings.json` copied out of the Unity Addressables
    build). Mods live in
    %userprofile%\\AppData\\LocalLow\\CascadeStudios\\MoSimulator\\Mods
  * Mods DO ship C# code: the .dll is literally "the robot's code". Robot code is
    a class deriving from a game robot base, driving `GenericJoint` /
    `GenericElevator` with `PidConstants`.
  * MoSim simulates FRC robots (community mods are "FRC robot mods"; the docs'
    walkthrough targets a Reefscape robot). It is not an FTC simulator.

Consequence, stated plainly: for an FTC robot like FAT MAN, MoSim can only be
driven with the FRC-equivalent mechanism set. The export therefore writes the
FRC-equivalent hierarchy + params + a working C# mod skeleton, and never claims
to simulate the servo-driven FTC turret/arm.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from string import Template

import numpy as np

README = """# MoSim prep for {robot} (FRC-equivalent)

Generated by Spool. Read this before dragging anything into Unity.

## What MoSim can and cannot do (verified)

* A mod is one folder with three files: `{mod}.bundle` (assets), `{mod}.dll`
  (robot code), `catalog.json` (metadata). When you build with Addressables you
  also copy `catalog.hash` and `settings.json` from
  `Library/com.unity.addressables/aa/Windows`.
* Install path: `%userprofile%\\AppData\\LocalLow\\CascadeStudios\\MoSimulator\\Mods`
* Mods **do** carry C# control code -- the .dll is the robot's code.
* MoSim simulates **FRC** robots. FAT MAN is an FTC robot, so this export is the
  FRC-equivalent mechanism set (Kraken/NEO numbers), not the two-servo FTC turret.

## Files here

| File | What it is |
|---|---|
| `hierarchy.json` | Node tree with transforms, joint axes, limits, masses |
| `params.json` | Per-joint gains and physical parameters the C# mod reads |
| `FatManMod.cs` | Robot code skeleton using the verified `GenericJoint` API |
| `README.md` | This file |

## Build steps (from the MoSim Lynk walkthrough)

1. **Model prep** -- import the mechanism meshes, one GameObject per moving part,
   origins at the joint axis.
2. **Hierarchy** -- build the tree in `hierarchy.json` exactly: the turret yaw is
   the parent of the hood and the flywheel; the arm hangs off the chassis.
3. **Colliders** -- convex mesh colliders on each moving part (MoSim does not
   derive them from the render mesh).
4. **Code** -- drop `FatManMod.cs` into `src/components/`, rename the namespace to
   your game's base class, and wire the `[SerializeField]` fields in the
   inspector to the joints and `PidConstants` assets.
5. **Mod building** -- Addressables group per mod, `modpack_metadata` label,
   custom build path, build, then copy `.bundle` + `.dll` + `catalog.json`
   (+ `catalog.hash`, `settings.json`) into the mods folder.

## What Spool deliberately does not do

No `.bundle` is produced: bundling needs the Unity editor and the team's mesh
assets, neither of which exists on this laptop. Spool gets you to step 1 with
real masses, inertias and gains; the bundle is a Unity-side job.
"""

CS_TEMPLATE = Template(
    """// Generated by Spool for ${robot}.
// MoSim robot code skeleton. Namespace and base class must match the current
// game (the docs' walkthrough uses ReefscapeRobotBase); MoSim is an FRC
// simulator, so these are the FRC-equivalent mechanisms.
//
// Verified API surface used here (docs.mosimulator.com, "Code" page):
//   GenericJoint, GenericElevator, PidConstants, JointAxis
//   joint.SetPid(pid) / joint.UpdatePid(pid) / joint.SetTargetAngle(rad)
//   joint.SetTargetAngle(rad).withAxis(JointAxis.X|Y|Z)
// and the GenericJoint.cs source (MoSim-Modding): JointAxis has X/Y/Z, and
//   joint.SetAngularVelocity(deg/s).WithAxis(JointAxis.X) is the velocity command.
// ReefscapeRobotBase / ReefscapeSetpoints are game-specific: rename for another
// game, and note that SetTarget on a joint is configuration-dependent, so the
// flywheel uses SetAngularVelocity (verified) rather than SetTarget.
namespace Prefabs.RobotMods.${ns}
{
    using UnityEngine;

    public class ${cls} : ReefscapeRobotBase
    {
        [Header("Joints")]
        [SerializeField] private GenericJoint turretYaw;
        [SerializeField] private GenericJoint hood;
        [SerializeField] private GenericJoint flywheel;
        [SerializeField] private GenericJoint arm;

        [Header("PID constants (from Spool)")]
        [SerializeField] private PidConstants turretYawPid;
        [SerializeField] private PidConstants hoodPid;
        [SerializeField] private PidConstants flywheelPid;
        [SerializeField] private PidConstants armPid;

        private float _turretTargetDeg;
        private float _hoodTargetDeg;
        private float _flywheelTargetRpm;
        private float _armTargetDeg;

        protected override void Start()
        {
            base.Start();
            // A joint cannot be used until its PID is initialised.
            turretYaw.SetPid(turretYawPid);
            hood.SetPid(hoodPid);
            flywheel.SetPid(flywheelPid);
            arm.SetPid(armPid);
        }

        private void LateUpdate()
        {
            // Lets the PID values be edited in the inspector at runtime.
            turretYaw.UpdatePid(turretYawPid);
            hood.UpdatePid(hoodPid);
            flywheel.UpdatePid(flywheelPid);
            arm.UpdatePid(armPid);
        }

        private void FixedUpdate()
        {
            switch (CurrentSetpoint)
            {
                case ReefscapeSetpoints.Stow:
                    _turretTargetDeg = 0f;
                    _hoodTargetDeg = ${hood_stow_deg}f;
                    _flywheelTargetRpm = 0f;
                    _armTargetDeg = 0f;
                    break;
                case ReefscapeSetpoints.Place:
                case ReefscapeSetpoints.L4:
                    _turretTargetDeg = 0f;
                    _hoodTargetDeg = ${hood_shot_deg}f;
                    _flywheelTargetRpm = ${flywheel_rpm}f;
                    _armTargetDeg = ${arm_place_deg}f;
                    break;
                default:
                    break;
            }

            ApplyTargets();
        }

        private void ApplyTargets()
        {
            turretYaw.SetTargetAngle(_turretTargetDeg * Mathf.Deg2Rad).withAxis(JointAxis.Y);
            hood.SetTargetAngle(_hoodTargetDeg * Mathf.Deg2Rad).withAxis(JointAxis.X);
            // Degrees/second (GenericJoint.cs), so rpm x 6.
            flywheel.SetAngularVelocity(_flywheelTargetRpm * 6f).WithAxis(JointAxis.X);
            arm.SetTargetAngle(_armTargetDeg * Mathf.Deg2Rad).withAxis(JointAxis.X);
        }
    }
}
"""
)


def _node(name: str, parent: str | None, position, rotation_deg, joint: dict | None, mass: float, inertia: float) -> dict:
    return {
        "name": name,
        "parent": parent,
        "position_m": [round(float(x), 5) for x in position],
        "rotation_deg": [round(float(x), 3) for x in rotation_deg],
        "mass_kg": round(float(mass), 5),
        "inertia_kgm2": round(float(inertia), 8),
        "joint": joint,
    }


def build_mosim(robot_doc: dict, frc_model, outdir: str | Path) -> dict[str, Path]:
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    nodes = [
        _node("chassis", None, (0, 0, 0), (0, 0, 0), None, frc_model.mass, 0.5),
    ]
    if "turret" in frc_model.rotary:
        t = frc_model.rotary["turret"]
        nodes.append(
            _node("turret_yaw", "chassis", (0, 0, 0.18), (0, 0, 0),
                  {"type": "revolute", "axis": "Y",
                   "limits_rad": list(t.limits) if t.limits else [-2.356, 2.356],
                   "target": 0.0}, 1.15, t.j_eff)
        )
    if "flywheel" in frc_model.rotary:
        f = frc_model.rotary["flywheel"]
        nodes.append(
            _node("flywheel", "turret_yaw", (0.0, 0.03, 0.08), (90, 0, 0),
                  {"type": "continuous", "axis": "X", "target_rpm": round(f.free_speed * 60 / (2 * math.pi) * 0.83, 1)},
                  f.params.get("load_mass_kg", 0.35), f.j_eff)
        )
    if "flower_arm" in frc_model.rotary:
        a = frc_model.rotary["flower_arm"]
        nodes.append(
            _node("arm", "chassis", (0.12, 0.0, 0.20), (0, 0, 0),
                  {"type": "revolute", "axis": "X",
                   "limits_rad": list(a.limits) if a.limits else [-0.2, 1.4],
                   "target": 0.4}, a.params.get("arm_mass_kg", 4.5), a.j_eff)
        )

    hierarchy = {
        "root": "chassis",
        "units": {"length": "m", "angle": "rad (joint limits), deg (transforms)",
                  "mass": "kg", "inertia": "kg*m^2"},
        "nodes": nodes,
        "drivetrain": {
            "type": "mecanum",
            "mass_kg": frc_model.mass,
            "wheel_radius_m": frc_model.drive.wheel_radius if frc_model.drive else 0.048,
            "max_forward_m_s": round(frc_model.drive.free_speed_forward, 3) if frc_model.drive else None,
        },
    }
    (outdir / "hierarchy.json").write_text(json.dumps(hierarchy, indent=2), encoding="utf-8")

    params = {"robot": robot_doc.get("name"), "note": "FRC-equivalent (MoSim is an FRC simulator)",
              "joints": {}}
    for name, axis in frc_model.rotary.items():
        params["joints"][name] = {
            "motor": axis.motor.key,
            "count": axis.n_motors,
            "gear_ratio": axis.gearbox.ratio,
            "efficiency": axis.gearbox.efficiency,
            "inertia_kgm2": axis.j_eff,
            "gains": axis.gains.as_dict(),
            "limits_rad": list(axis.limits) if axis.limits else None,
        }
    (outdir / "params.json").write_text(json.dumps(params, indent=2), encoding="utf-8")

    flywheel_rpm = 0.0
    if "flywheel" in frc_model.rotary:
        flywheel_rpm = frc_model.rotary["flywheel"].free_speed * 0.83 * 60 / (2 * math.pi)
    cs = CS_TEMPLATE.substitute(
        robot=robot_doc.get("name", "robot").replace(" ", ""),
        ns="Spool",
        cls="SpoolRobot",
        hood_stow_deg="10",
        hood_shot_deg="55",
        flywheel_rpm=f"{flywheel_rpm:.0f}",
        arm_place_deg="60",
    )
    (outdir / "SpoolRobot.cs").write_text(cs, encoding="utf-8")
    (outdir / "README.md").write_text(
        README.format(robot=robot_doc.get("name", "robot"), mod="SpoolRobot"), encoding="utf-8"
    )
    return {
        "hierarchy": outdir / "hierarchy.json",
        "params": outdir / "params.json",
        "cs": outdir / "SpoolRobot.cs",
        "readme": outdir / "README.md",
    }
