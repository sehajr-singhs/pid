"""FTC Dashboard / Panels config export.

A plain `@Config` class: static doubles that the dashboard rewrites live while the
robot runs. This is the intended way to tune a flywheel or turret on an FTC robot
with Panels (Panels reads the same FTC Dashboard config protocol).

The class deliberately keeps kS/kV/kA separate from kP/kI/kD so a student can see
which numbers came from CAD and which came from the loop.
"""

from __future__ import annotations

from pathlib import Path
from string import Template

TEMPLATE = Template(
    """package org.firstinspires.ftc.teamcode.spool;

// -----------------------------------------------------------------------------
// Generated by Spool for ${robot_name}.
// FTC Dashboard / Panels config. Static fields are live-editable from the
// dashboard while the robot is running.
//
// Gains in this file are per-output-axis SI:
//   kS  volts
//   kV  volts per (rad/s)
//   kA  volts per (rad/s^2)
//   kG  volts (gravity term, 0 for non-gravity axes)
// kP/kI/kD come from the Spool simulation (differential evolution over the
// step response), not from a rule of thumb.
// -----------------------------------------------------------------------------

import com.acmerobotics.dashboard.config.Config;

@Config
public final class SpoolGains {
    private SpoolGains() {}

${blocks}
}
"""
)

BLOCK = Template(
    """    /** ${label} */
    public static class ${cls} {
        // --- feedforward (CAD + datasheet) ---
        public static double kS = ${kS};
        public static double kV = ${kV};
        public static double kA = ${kA};
        public static double kG = ${kG};
        // --- feedback (simulated tune) ---
        public static double kP = ${kP};
        public static double kI = ${ki};
        public static double kD = ${kd};
        // --- limits ---
        public static double MAX_VOLTS = ${max_volts};
        public static double TARGET = ${target};
    }
"""
)


def _cls_name(name: str) -> str:
    return "".join(part.capitalize() for part in name.replace("-", "_").split("_"))


def build_dashboard(robot_doc: dict, gains_table: list[dict], outdir: str | Path) -> Path:
    """Write SpoolGains.java. `gains_table` is a list of dicts with gains + tuning."""
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    blocks = []
    for entry in gains_table:
        g = entry["gains"]
        tune = entry.get("tuned", {})
        blocks.append(
            BLOCK.substitute(
                label=entry.get("label", entry["name"]),
                cls=_cls_name(entry["name"]),
                kS=f"{g['kS']:.5f}",
                kV=f"{g['kV']:.6f}",
                kA=f"{g['kA']:.6f}",
                kG=f"{g['kG']:.5f}",
                kP=f"{tune.get('kp', 0.0):.5f}",
                ki=f"{tune.get('ki', 0.0):.5f}",
                kd=f"{tune.get('kd', 0.0):.5f}",
                max_volts=f"{g.get('saturation_voltage', 12.0):.1f}",
                target=f"{entry.get('target', 0.0):.4f}",
            )
        )
    path = outdir / "SpoolGains.java"
    path.write_text(
        TEMPLATE.substitute(robot_name=robot_doc.get("name", "robot"), blocks="\n".join(blocks)),
        encoding="utf-8",
    )
    return path
