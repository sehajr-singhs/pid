CHECKLIST = """# Pedro Pathing tuning checklist for {robot}

Generated by Piπd. The numbers in `Constants.java` are CAD-derived starting
points. Every one of these procedures is a real AutoTune step documented at
https://pedropathing.com/docs/pathing/tuning/foresight -- run them in this order
and paste the result back over the matching block.

1. Build and upload with the Foresight tuner added to your Tuning class:
       @Tuner
       public static Procedure foresightTuner() {{
           return new ForesightTuner(
               (hardwareMap) -> new PinpointLocalizer(hardwareMap, Constants.localizerConfig),
               (hardwareMap) -> new Mecanum(hardwareMap, Constants.drivetrainConfig));
       }}
2. Connect to the Robot Controller and open http://192.168.43.1:10158
3. Run **Foresight Procedure**:
   - Forward Velocity Identification      -> replaces maxAchievableForwardVelocity
                                            (Piπd starting value: {max_forward:.2f} in/s)
   - Strafe Velocity Identification       -> maxAchievableStrafeVelocity
                                            (Piπd: {max_strafe:.2f} in/s)
   - Forward Deceleration Identification  -> naturalForwardDeceleration
                                            (Piπd: {decel_forward:.2f} in/s^2)
   - Strafe Deceleration Identification   -> naturalStrafeDeceleration
                                            (Piπd: {decel_strafe:.2f} in/s^2)
   - Heading Braking Identification       -> headingBrakeCoefficients
   - Heading Tuner                        -> headingFeedback kP
                                            (Piπd starting value: {kp_heading:.3f})
   - Forward Braking Identification       -> coast / brake / linearBrakeCoefficients
   - Strafe Braking Identification        -> as above, lateral
   - Forward Translational Tuner          -> forwardTranslational kP + coast/brake kV
   - Strafe Translational Tuner           -> strafeTranslational kP
4. Then run **Tests** to verify the follower end to end.

Two values Piπd cannot measure and Pedro can:
  * roller slip on your actual foam tile ({strafe_eff:.2f} was assumed for strafe)
  * rolling resistance ({mu_roll:.3f} was assumed, x g)
"""


def build_pedro(robot_doc: dict, model, outdir: str | Path) -> dict[str, Path]:
    """Write Constants.java + the tuning checklist. Returns the paths written."""
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    drive = model.drive
    if drive is None:
        raise ValueError("Pedro export needs a drivetrain mechanism")

    free_in_s = drive.free_speed_forward / M_PER_IN
    drive_eff = 0.97          # belt + bearing loss from full free speed under load
    strafe_eff = drive.strafe_efficiency
    mu_roll = drive.mu_rolling

    max_forward = free_in_s * drive_eff
    max_strafe = max_forward * strafe_eff
    decel_forward = mu_roll * G / M_PER_IN
    decel_strafe = decel_forward * 1.15        # rollers scrub harder sideways

    # Translational kP: pole placement on kA with a path-following bandwidth of
    # 2 rad/s, converted from volts/metre to volts/inch.
    ka = drive.gains_forward.kA
    kp_forward_per_in = (2.0**2) * ka / (1.0 / M_PER_IN)
    kp_heading = (3.0**2) * _yaw_ka(drive, robot_doc)

    values = {
        "robot_name": robot_doc.get("name", "robot"),
        "forward_free_in_s": f"{free_in_s:.2f}",
        "drive_eff": f"{drive_eff:.2f}",
        "strafe_eff": f"{strafe_eff:.2f}",
        "mu_roll": f"{mu_roll:.3f}",
        "pod_x_in": "2.187",
        "pod_y_in": "-4.572",
        "kp_forward": f"{kp_forward_per_in:.4f}",
        "kp_forward_secondary": f"{kp_forward_per_in / 3.0:.4f}",
        "kp_strafe": f"{kp_forward_per_in / strafe_eff:.4f}",
        "kp_strafe_secondary": f"{kp_forward_per_in / strafe_eff / 3.0:.4f}",
        "max_forward": f"{max_forward:.2f}",
        "max_strafe": f"{max_strafe:.2f}",
        "decel_forward": f"{decel_forward:.2f}",
        "decel_strafe": f"{decel_strafe:.2f}",
        "kp_heading": f"{kp_heading:.4f}",
        "linear_brake_x": "0.10605894992901523",
        "linear_brake_y": "0.08719146175596092",
    }

    constants = outdir / "Constants.java"
    constants.write_text(TEMPLATE.substitute(values), encoding="utf-8")

    checklist = outdir / "PEDRO_TUNING_CHECKLIST.md"
    checklist.write_text(
        CHECKLIST.format(
            robot=robot_doc.get("name", "robot"),
            max_forward=max_forward,
            max_strafe=max_strafe,
            decel_forward=decel_forward,
            decel_strafe=decel_strafe,
            kp_heading=kp_heading,
            strafe_eff=strafe_eff,
            mu_roll=mu_roll,
        ),
        encoding="utf-8",
    )

    values_out = outdir / "pedro_values.json"
    values_out.write_text(
        json.dumps(
            {
                "units": {
                    "maxAchievable*Velocity": "in/s",
                    "natural*Deceleration": "in/s^2",
                    "controllers": "volts per inch of error (pid interpretation)",
                },
                "derived": {
                    "maxAchievableForwardVelocity": max_forward,
                    "maxAchievableStrafeVelocity": max_strafe,
                    "naturalForwardDeceleration": decel_forward,
                    "naturalStrafeDeceleration": decel_strafe,
                    "heading_kP": kp_heading,
                    "translational_kP_per_inch": kp_forward_per_in,
                },
                "assumptions": {
                    "drive_efficiency": drive_eff,
                    "strafe_efficiency": strafe_eff,
                    "mu_rolling": mu_roll,
                    "pod_offsets": "2.187 / -4.572 in taken from the Pedro docs example: set yours",
                },
                "placeholder_fields": [
                    "coast",
                    "brake",
                    "headingBrakeCoefficients",
                    "linearBrakeCoefficients",
                    "quadraticBrakeCoefficients",
                ],
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return {"constants": constants, "checklist": checklist, "values": values_out}


def _yaw_ka(drive, robot_doc: dict) -> float:
    """kA for yaw: J_z * R / (4 * eta * G * kt), using the CAD yaw inertia."""
    j_z = 0.2428
    try:
        mass_props = robot_doc.get("_mass_properties", {})
        j_z = float(mass_props.get("principalInertia", [j_z])[2])
    except (TypeError, IndexError, ValueError):
        pass
    motor = drive.motor
    return j_z * motor.resistance / (4 * drive.gearbox.efficiency * drive.gearbox.ratio * motor.kt)
